import { readFileSync, writeFileSync } from 'node:fs';
import { migrationFiles } from './migration-files.mjs';

try {
  const manifest = migrationFiles(new URL('../migrations/', import.meta.url));
  const output = new URL('../src/generated/migrations.ts', import.meta.url);
  const content = '// Generated by scripts/migration-manifest.mjs; do not edit.\n'
    + `export const migrationManifest = ${JSON.stringify(manifest, null, 2)} as const;\n`
    + 'export const expectedMigrations: readonly string[] = migrationManifest.map(entry => entry.name);\n';
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== content) throw new Error('Migration manifest drift; run npm run migrations:generate in the API workspace.');
    console.info('Migration manifest is current.');
  } else {
    writeFileSync(output, content);
    console.info('Migration manifest generated.');
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : 'Migration manifest generation failed.');
  process.exitCode = 1;
}
